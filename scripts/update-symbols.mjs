// Regenerates src/engine/symbols.data.js from FTMO's public symbols endpoint.
// Usage: node scripts/update-symbols.mjs   (run before deploy to refresh specs)
import { writeFile } from 'node:fs/promises';

const SRC = 'https://ftmo.com/wp-json/ftmo/symbols';
const res = await fetch(SRC, { headers: { 'User-Agent': 'Mozilla/5.0' } });
if (!res.ok) throw new Error(`FTMO symbols fetch failed: HTTP ${res.status}`);
const { data } = await res.json();
const now = new Date().toISOString();

const CLASS = { 'Forex': 'forex', 'Exotics': 'exotic', 'Metals CFD': 'metals', 'Cash CFD': 'cash', 'Crypto CFD': 'crypto', 'Equities CFD': 'stocks' };

const rows = data.symbols
  .filter(s => s.active && s.start <= now && now <= s.end && !s.isExpiringContract)
  .map(s => {
    const forexLike = s.marginCalculation === 'forex';
    const symbol = forexLike || s.assetClass === 'Metals CFD' ? s.code.replace('/', '') : s.code;
    // [symbol, class, contractSize, marginCcy, profitCcy, calc, commType, commRoundTurn, levSwing, levStandard, maxVolume, digits]
    return [symbol, CLASS[s.assetClass] ?? 'other', s.contractSize, s.marginCurrency, s.profitCurrency,
      forexLike ? 'forex' : 'cfd', s.commissionType === 'flat_USD' ? 'usd' : 'pct', s.commission,
      s.leverageSwing, s.leverageStandard, s.maxTradeVolume, s.digits];
  })
  .sort((a, b) => a[0].localeCompare(b[0]));

const out = `// AUTO-GENERATED by scripts/update-symbols.mjs from ${SRC}
// Fetched: ${now.slice(0, 10)} — ${rows.length} symbols. Do not edit by hand.
// [symbol, class, contractSize, marginCcy, profitCcy, calc, commType, commRoundTurn, levSwing, levStandard, maxVolume, digits]
// commType 'pct' = % of notional (round turn), 'usd' = USD per lot (round turn).
export const SYMBOLS_UPDATED = '${now.slice(0, 10)}';
export const SYMBOL_ROWS = [
${rows.map(r => '  ' + JSON.stringify(r)).join(',\n')},
];
`;
await writeFile(new URL('../src/engine/symbols.data.js', import.meta.url), out);
console.log(`Wrote ${rows.length} symbols`);
